/**
 * Zod schema for validating `aocs` insert payloads sent via the API.
 *
 * **Generated from** `aocsTable` by `drizzle-zod`'s `createInsertSchema`.
 *
 * **Required fields** (caller must supply):
 *  - `id`            — UUID primary key.
 *  - `entityCode`    — FK to `entities.code`.
 *  - `frameworkCode` — short framework code (e.g. `"PCI-DSS"`).
 *  - `title`         — descriptive AoC title.
 *
 * **Optional / defaulted fields**:
 *  - `status`          — defaults to `"current"` if omitted.
 *  - `frameworkName`   — nullable; provide for denormalised display.
 *  - `qsaCompany`      — nullable; omit for SAQ self-assessments.
 *  - `qsaLead`         — nullable.
 *  - `issuedDate`      — nullable; set when the QSA signs the document.
 *  - `expiresDate`     — nullable; typically `issuedDate` + 12 months.
 *  - `period`          — nullable; provide a fiscal year label (e.g. `"FY2025"`).
 *  - `result`          — nullable; set from the final ROC/AoC outcome.
 *  - `controlsCovered` — nullable; informational count.
 *  - `findings`        — nullable; count of open findings at issuance.
 *  - `filename`        — nullable; set after file upload.
 *  - `filePath`        — nullable; set after file upload.
 *  - `notes`           — nullable.
 *
 * **Omitted fields**:
 *  - `createdAt` — handled by the database `defaultNow()`.
 *
 * @example
 * ```ts
 * const payload = insertAocSchema.parse({
 *   id: crypto.randomUUID(),
 *   entityCode: "gopuff",
 *   frameworkCode: "PCI-DSS",
 *   frameworkName: "PCI DSS 4.0",
 *   title: "PCI DSS AoC – Gopuff FY2025",
 *   status: "current",
 *   qsaCompany: "Coalfire",
 *   issuedDate: "2025-03-15",
 *   expiresDate: "2026-03-14",
 *   period: "FY2025",
 *   result: "Compliant",
 * });
 * await db.insert(aocsTable).values(payload);
 * ```
 */
export const insertAocSchema = createInsertSchema(aocsTable).omit({ createdAt: true });

