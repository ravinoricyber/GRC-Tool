/**
 * Zod schema for validating `evidence_requests` insert payloads sent via the API.
 *
 * **Generated from** `evidenceRequestsTable` by `drizzle-zod`'s `createInsertSchema`.
 *
 * **Required fields** (caller must supply):
 *  - `id`            — UUID primary key.
 *  - `code`          — unique human-readable code (`EVR-YYYY-NNNN`).
 *  - `controlRef`    — control reference number (e.g. `"1.2.1"`).
 *  - `frameworkCode` — parent framework code (e.g. `"PCI-DSS"`).
 *  - `entityCode`    — owning entity code (e.g. `"gopuff"`).
 *  - `title`         — short descriptive title of the request.
 *
 * **Optional / defaulted fields**:
 *  - `status`      — defaults to `"requested"` if omitted.
 *  - `priority`    — defaults to `"medium"` if omitted.
 *  - `assessmentId`, `controlId`, `controlName`, `frameworkName`,
 *    `description`, `assignee`, `requestedBy`, `dueDate` — nullable; may be omitted.
 *  - `approvedAt`  — nullable; set by application logic on approval.
 *
 * **Omitted fields**:
 *  - `requestedAt` — handled by the database `defaultNow()`.
 *  - `createdAt`   — handled by the database `defaultNow()`.
 *
 * @example
 * ```ts
 * const payload = insertEvidenceSchema.parse({
 *   id: crypto.randomUUID(),
 *   code: "EVR-2026-0001",
 *   controlRef: "1.2.1",
 *   frameworkCode: "PCI-DSS",
 *   entityCode: "gopuff",
 *   title: "Firewall rule export – PCI segment",
 *   priority: "high",
 *   assignee: "alice@gopuff.com",
 *   dueDate: "2026-03-31",
 * });
 * await db.insert(evidenceRequestsTable).values(payload);
 * ```
 */
export const insertEvidenceSchema = createInsertSchema(evidenceRequestsTable).omit({ requestedAt: true, createdAt: true });

