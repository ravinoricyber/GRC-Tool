/**
 * `InsertVendor` — shape of the object required to insert a new vendor row.
 *
 * Inferred from `insertVendorSchema` (the Zod insert schema).
 *
 * **Usage**: API request body validation, vendor onboarding endpoints, seed scripts.
 *
 * @example
 * ```ts
 * async function addVendor(body: InsertVendor): Promise<Vendor> {
 *   const validated = insertVendorSchema.parse(body);
 *   const [row] = await db.insert(vendorsTable).values(validated).returning();
 *   return row;
 * }
 * ```
 */
export type InsertVendor = z.infer<typeof insertVendorSchema>;

/**
 * `Vendor` — full shape of a row returned by a SELECT on `vendorsTable`.
 *
 * Inferred from the Drizzle table definition via `$inferSelect`.
 *
 * **Usage**: API response types, TPSP register views, vendor risk dashboards,
 * certification expiry alert jobs.
 *
 * @example
 * ```ts
 * // Find all critical vendors with expiring certifications
 * const expiring: Vendor[] = await db
 *   .select()
 *   .from(vendorsTable)
 *   .where(
 *     and(
 *       eq(vendorsTable.riskLevel, "critical"),
 *       eq(vendorsTable.hasPciCertification, true),
 *       lte(vendorsTable.certificationExpiry, thirtyDaysFromNow),
 *     ),
 *   );
 * ```
 */
export type Vendor = typeof vendorsTable.$inferSelect;
