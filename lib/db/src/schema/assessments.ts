/**
 * `InsertAssessment` — shape of the object required to insert a new assessment row.
 *
 * Inferred from `insertAssessmentSchema` (the Zod insert schema).
 *
 * **Usage**: API request body validation, assessment creation endpoints, seed scripts.
 *
 * @example
 * ```ts
 * async function createAssessment(body: InsertAssessment): Promise<Assessment> {
 *   const validated = insertAssessmentSchema.parse(body);
 *   const [row] = await db.insert(assessmentsTable).values(validated).returning();
 *   return row;
 * }
 * ```
 */
export type InsertAssessment = z.infer<typeof insertAssessmentSchema>;

/**
 * `Assessment` — full shape of a row returned by a SELECT on `assessmentsTable`.
 *
 * Inferred from the Drizzle table definition via `$inferSelect`.
 *
 * **Usage**: API response types, assessment dashboard components, evidence request
 * management forms (to show which assessment an EVR belongs to).
 *
 * @example
 * ```ts
 * const activeAssessments: Assessment[] = await db
 *   .select()
 *   .from(assessmentsTable)
 *   .where(
 *     inArray(assessmentsTable.status, ["planning", "fieldwork", "reporting"]),
 *   );
 * ```
 */
export type Assessment = typeof assessmentsTable.$inferSelect;
